using System.Globalization;
using StormConnect.Protocol;

namespace StormConnect.Desktop.Services;

public sealed record LanguageOption(string Code, string DisplayName)
{
    public override string ToString() => DisplayName;
}

/// <summary>
/// Complete 11-language STORM Ecosystem localization service.
/// Automatically detects OS system language on first launch and enforces zero em-dashes.
/// </summary>
public static class LocalizationService
{
    public static readonly IReadOnlyList<LanguageOption> Languages =
    [
        new("ru", "Русский"),
        new("en", "English"),
        new("de", "Deutsch"),
        new("fr", "Français"),
        new("zh", "简体中文"),
        new("ko", "한국어"),
        new("ja", "日本語"),
        new("es", "Español"),
        new("it", "Italiano"),
        new("pt", "Português"),
        new("hi", "हिन्दी")
    ];

    public static string CurrentLanguage { get; private set; } = DetectSystemLanguage();

    public static event Action? LanguageChanged;

    public static string DetectSystemLanguage()
    {
        var two = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
        return Languages.Any(l => l.Code == two) ? two : "en";
    }

    public static void SetLanguage(string codeOrAuto)
    {
        string target = string.Equals(codeOrAuto, "auto", StringComparison.OrdinalIgnoreCase)
            ? DetectSystemLanguage()
            : (Languages.Any(l => l.Code == codeOrAuto) ? codeOrAuto : "en");
        CurrentLanguage = target;
        LanguageChanged?.Invoke();
    }

    public static string T(string key)
    {
        if (Strings.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(key, out var val))
            return val;
        if (Strings["en"].TryGetValue(key, out var enVal))
            return enVal;
        return key;
    }

    public static string LocalizeMode(ConnectionMode mode) => mode switch
    {
        ConnectionMode.LanDirect => T("ModeLanDirect"),
        ConnectionMode.DirectIp => T("ModeDirectIp"),
        ConnectionMode.P2pUdp => T("ModeP2pUdp"),
        ConnectionMode.WssRelay => T("ModeWssRelay"),
        _ => mode.ToString()
    };

    public static string LocalizeMode(string rawMode) => rawMode switch
    {
        "LanDirect" => T("ModeLanDirect"),
        "DirectIp" => T("ModeDirectIp"),
        "P2pUdp" => T("ModeP2pUdp"),
        "WssRelay" => T("ModeWssRelay"),
        _ => rawMode
    };

    public static string LocalizeAuditAction(string rawAction) => rawAction switch
    {
        "Outgoing Connected" or "OutgoingConnected" => T("AuditOutgoingConnected"),
        "Incoming Connected" or "IncomingConnected" => T("AuditIncomingConnected"),
        _ => rawAction
    };

    public static IEnumerable<KeyValuePair<string, string>> GetAllStringsForLanguage(string lang)
    {
        return Strings.TryGetValue(lang, out var dict) ? dict : Strings["en"];
    }

